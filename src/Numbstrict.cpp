static const Char* pointerAt(const Element& source, StringIt it) {														// `source` must not be empty
	return &*source.begin() + (it - source.begin());
}

static StringIt iteratorAt(const Element& source, const Char* pointer) {												// `source` must not be empty
	return source.begin() + (pointer - &*source.begin());
}

static bool startsHexadecimal(const Char* p, const Char* e) {															// a bare 0x is a 0 and an x, where a scan stops
	return (e - p >= 3 && p[0] == '0' && p[1] == 'x' && fromHex(p[2]) >= 0);
}

static bool looksOctal(const Char* b, const Char* e) {																	// digits alone with a leading zero, octal in C
	if (e - b < 2 || *b != '0') {
		return false;
	}
	const Char* p = b;
	while (p != e && *p >= '0' && *p <= '9') {
		++p;
	}
	return p == e;
}

/*
	`overflow` is null, or the first digit that would take `ui` past `highest`, where `ui` then stays: the caller
	fails there or saturates.
*/
static const Char* readUnsigned(const Char* p, const Char* e, int base, uint64_t highest, uint64_t& ui
		, const Char*& overflow) {
	const bool prefixed = (base == 0 && startsHexadecimal(p, e));
	const bool hex = (prefixed || base == 16);
	base = (hex ? 16 : 10);
	const uint64_t cutoff = highest / base;																				// strtol's test: no division per digit
	const int lastDigit = static_cast<int>(highest % base);
	ui = 0;
	overflow = 0;
	if (prefixed) {
		p += 2;
	}
	for (int v; p != e && (v = (hex ? fromHex(*p) : (*p >= '0' && *p <= '9' ? *p - '0' : -1))) >= 0; ++p) {
		if (overflow == 0 && (ui > cutoff || (ui == cutoff && v > lastDigit))) {
			overflow = p;
		}
		ui = (overflow != 0 ? highest : ui * base + v);
	}
	return p;
}

template<typename T> static typename std::make_unsigned<T>::type highestMagnitude(bool negative) {
	typedef typename std::make_unsigned<T>::type UT;
	const UT top = std::numeric_limits<UT>::max();
	return static_cast<UT>(std::is_signed<T>() ? (top >> 1) + (negative ? 1 : 0) : top);
}

template<typename T> bool Parser::tryToParseInteger(T& i) {
	typedef typename std::make_unsigned<T>::type UT;
	whiteAndComments();
	i = 0;
	if (eof()) {
		return false;
	}
	const Char* const b = pointerAt(source, p);
	const Char* const e = pointerAt(source, source.end());
	const bool negative = (*b == '-' && std::is_signed<T>());
	const Char* const d = b + ((negative || *b == '+') ? 1 : 0);
	uint64_t ui;
	const Char* overflow;
	const Char* const q = readUnsigned(d, e, 0, highestMagnitude<T>(negative), ui, overflow);
	const bool leadingZero = looksOctal(d, q);
	p = iteratorAt(source, leadingZero ? d + 1 : overflow != 0 ? overflow : q);
	if (q == d || leadingZero || overflow != 0) {
		return false;
	}
	i = rewrap<T>(static_cast<UT>(negative ? 0 - ui : ui));
	whiteAndComments();
	return eof();
}

bool Parser::tryToParse(int8_t& i) { return tryToParseInteger(i); }
bool Parser::tryToParse(uint8_t& i) { return tryToParseInteger(i); }
bool Parser::tryToParse(int16_t& i) { return tryToParseInteger(i); }
bool Parser::tryToParse(uint16_t& i) { return tryToParseInteger(i); }
bool Parser::tryToParse(int32_t& i) { return tryToParseInteger(i); }
bool Parser::tryToParse(uint32_t& i) { return tryToParseInteger(i); }
bool Parser::tryToParse(int64_t& i) { return tryToParseInteger(i); }
bool Parser::tryToParse(uint64_t& i) { return tryToParseInteger(i); }

bool Parser::tryToParse(bool& b) {
	b = false;
	whiteAndComments();
	if (left() >= 5 && std::equal(p, p + 5, "false")) {
		p += 5;
	} else if (left() >= 4 && std::equal(p, p + 4, "true")) {
		b = true;
		p += 4;
	} else {
		return false;
	}
	whiteAndComments();
	return eof();
}

void Parser::throwError() {
	size_t offset = source.offset(p);
	const LineAndColumn lineAndColumn = source.lineAndColumn(p);
	throw ParsingError(source.filename(), offset, lineAndColumn.first, lineAndColumn.second);
}

bool Parser::comment() {
	if (left() < 2 || p[0] != '/') {
		return false;
	}
	if (p[1] == '/') {
		p += 2;
		while (!eof() && *p != '\r' && *p != '\n' && (static_cast<UChar>(*p) >= 32 || *p == '\t')) {
			++p;
		}
		return true;
	} else if (p[1] == '*') {
		p += 2;

		// Refrain from using recursion when it is easy, to prevent stack overflow.
		int nestCounter = 1;
		while (!eof() && nestCounter > 0) {
			if (static_cast<UChar>(*p) < 32 && *p != '\r' && *p != '\n' && *p != '\t') {
				break;
			}
			if (left() >= 2 && p[0] == '/' && p[1] == '*') {
				++nestCounter;
				p += 2;
			} else if (left() >= 2 && p[0] == '*' && p[1] == '/') {
				--nestCounter;
				p += 2;
			} else {
				++p;
			}
		}
		return true;
	} else {
		return false;
	}
}

bool Parser::whiteAndComments() {
	const StringIt b = p;
	while (!eof()) {
		if (!comment()) {
			if (!(*p == ' ' || *p == '\t' || *p == '\r' || *p == '\n')) {
				break;
			}
			++p;
		}
	}
	return p != b;
}

bool Parser::horizontalWhiteAndComments() {
	const StringIt b = p;
	while (!eof()) {
		if (!comment()) {
			if (!(*p == ' ' || *p == '\t')) {
				break;
			}
			++p;
		}
	}
	return p != b;
}

template<typename C> bool isLeadingIdentifierChar(const C c) {
	return ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || c == '_');
}

template<typename C> bool isIdentifierChar(const C c) {
	return ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_');
}

template<typename S> bool keyNeedsQuoting(const S& key) {
	typename S::const_iterator p = key.begin();
	const typename S::const_iterator e = key.end();
	if (p == e || !isLeadingIdentifierChar(*p)) {
		return true;
	}
	++p;
	while (p != e) {
		if (!isIdentifierChar(*p)) {
			return true;
		}
		++p;
	}
	return false;
}

bool Parser::parseIdentifier(String& identifier) {
	const StringIt b = p;
	if (eof() || !isLeadingIdentifierChar(*p)) {
		return false;
	}
	++p;
	while (!eof() && isIdentifierChar(*p)) {
		++p;
	}
	identifier = String(b, p);
	return true;
}

bool Parser::quotedStringElement(Element& element) {
	assert(!eof() && (*p == '\"' || *p == '\''));
	const StringIt b = p;
	const Char quoteChar = *p;
	++p;
	while (!eof() && *p != quoteChar) {
		if (*p == '\\') {
			++p;
		}
		if (!eof()) {
			++p;
		}
	}
	const bool ok = !eof();
	if (ok) {
		++p;
	}
	element = Element(source, b, p);
	return ok;
}

template<typename C> bool Parser::quotedString(std::basic_string<C>& string) {
	if (eof() || !(*p == '\"' || *p == '\'')) {
		return false;
	}
	return genericUnquoteString(p, source.end(), string);
}

template<typename C> void Parser::unquotedText(std::basic_string<C>& string) {
	whiteAndComments();
	do {
		StringIt b = p;
		while (!eof() && isTextChar(*p) && !(left() >= 2 && p[0] == '/' && (p[1] == '/' || p[1] == '*'))) {
			++p;
		}
		if (b != p) {
			if (!string.empty()) {
				string += ' ';
			}
			string.insert(string.end(), b, p);
		}
	} while (whiteAndComments());
}

template<typename C> bool Parser::stringOrText(std::basic_string<C>& string) {
	string.clear();
	whiteAndComments();
	if (eof() || !(*p == '\"' || *p == '\'')) {
		unquotedText(string);
	} else if (quotedString(string)) {
		whiteAndComments();
	} else {
		return false;
	}
	return eof();
}

bool Parser::tryToParse(String& string) { return stringOrText(string); }
bool Parser::tryToParse(WideString& string) { return stringOrText(string); }

bool Parser::blockElement(Element& element) {
	element = Element(source, p, p);
	if (eof() || *p != '{') {
		return false;
	}
	++p;
	int nestCounter = 1;
	while (!eof() && nestCounter > 0) {
		Element dummy;
		switch (*p) {
			case '\"': case '\'': if (!quotedStringElement(dummy)) return false; break;
			case '/': if (!comment()) ++p; break;
			case '{': ++nestCounter; ++p; break;
			case '}': --nestCounter; ++p; break;
			default: ++p;
		}
	}
	element = Element(element, element.begin(), p);
	return (nestCounter == 0);
}

bool Parser::unquotedTextElement(Element& element) {
	element = Element(source, p, p);
	do {
		StringIt b = p;
		while (!eof() && isTextChar(*p) && !(left() >= 2 && p[0] == '/' && (p[1] == '/' || p[1] == '*'))) {
			++p;
		}
		if (b != p) {
			element = Element(element, element.begin(), p);
		}
	} while (horizontalWhiteAndComments());
	return true;
}

bool Parser::valueElement(Element& element) {
	if (!eof() && *p == '{') {
		return blockElement(element);
	} else if (!eof() && (*p == '\"' || *p == '\'')) {
		return quotedStringElement(element);
	} else if (!eof() && isTextChar(*p)) {
		return unquotedTextElement(element);
	} else {
		element = Element(source, p, p);
		return true;
	}
}

static void toKeyString(String& d, const String& s) { d = s; }
static void toKeyString(WideString& d, const String& s) { d = WideString(s.begin(), s.end()); }

template<typename C> bool Parser::keyValuePair(std::map<std::basic_string<C>, Element>& elements) {
	std::pair<std::basic_string<C>, Element> kv;
	const StringIt b1 = p;
	String identifier;
	if (parseIdentifier(identifier)) {
		toKeyString(kv.first, identifier);
	} else if (!quotedString(kv.first)) {
		return false;
	}
	horizontalWhiteAndComments();
	kv.second = Element(source, p, p);
	if (eof() || *p != ':') {
		return false;
	}
	++p;
	horizontalWhiteAndComments();
	if (!valueElement(kv.second)) {
		return false;
	}
	horizontalWhiteAndComments();
	if (!elements.insert(kv).second) {
		p = b1;
		return false;
	}
	return true;
}

bool Parser::nextElement() {
	bool optionalComma = (!eof() && (*p == '\r' || *p == '\n'));
	whiteAndComments();
	if (eof() || *p == '}') {
		return true;
	}
	if (*p == ',') {
		++p;
		whiteAndComments();
		return true;
	}
	return optionalComma;
}

template<typename C> bool Parser::keyValueElements(std::map<std::basic_string<C>, Element>& elements) {
	if (!eof() && *p == ':') {	// special empty struct syntax { : }
		++p;
		whiteAndComments();
	} else {
		while (!eof() && *p != '}') {
			if (!keyValuePair(elements)) {
				return false;
			}
			if (!nextElement()) {
				return false;
			}
		}
	}
	return true;
}

bool Parser::valueListElements(Array& elements) {
	while (!eof() && *p != '}') {
		Element v(source, p, p);
		if (!valueElement(v)) {
			return false;
		}
		horizontalWhiteAndComments();
		elements.push_back(v);
		if (!nextElement()) {
			return false;
		}
	}
	return true;
}

template<typename S> bool Parser::tryToParseStruct(S& elements) {
	elements.clear();
	whiteAndComments();
	if (!eof() && *p == '{') {
		++p;
		whiteAndComments();
		if (!keyValueElements(elements)) {
			return false;
		}
		if (eof() || *p != '}') {
			return false;
		}
		++p;
		whiteAndComments();
	} else if (!keyValueElements(elements)) {
		return false;
	}
	return eof();
}

bool Parser::tryToParse(Struct& elements) {
	return tryToParseStruct(elements);
}

bool Parser::tryToParse(WideStruct& elements) {
	return tryToParseStruct(elements);
}

bool Parser::tryToParse(Array& elements) {
	elements.clear();
	whiteAndComments();
	if (!eof() && *p == '{') {
		++p;
		whiteAndComments();
		if (!valueListElements(elements)) {
			return false;
		}
		if (eof() || *p != '}') {
			return false;
		}
		++p;
		whiteAndComments();
	} else if (!valueListElements(elements)) {
		return false;
	}
	return eof();
}

bool Parser::tryToParse(Variant& toVariant) {
	toVariant = Variant();
	whiteAndComments();
	if (!eof()) {
		const StringIt b = p;
		switch (*p) {
			case 't': case 'f': {
				if (tryToParse(toVariant.boolean)) {
					toVariant.type = Variant::BOOLEAN;
					return true;
				}
				break;
			}
			case 'i': // inf
			case 'n': // nan
			case '+': case '-': case '.':
			case '0': case '1': case '2': case '3': case '4':
			case '5': case '6': case '7': case '8': case '9': {
				if (tryToParse(toVariant.integer)) {
					toVariant.type = Variant::INTEGER;
					return true;
				}
				p = b;
				if (tryToParse(toVariant.unsignedInteger)) {
					toVariant.type = Variant::UNSIGNED_INTEGER;
					return true;
				}
				p = b;
				if (tryToParse(toVariant.real)) {
					toVariant.type = Variant::REAL;
					return true;
				}
				break;
			}
			case '{': {
				if (tryToParse(toVariant.array)) {
					toVariant.type = Variant::ARRAY;
					return true;
				}
				p = b;
				if (tryToParse(toVariant.structure)) {
					toVariant.type = Variant::STRUCT;
					return true;
				}
				return false;
			}
		}
		p = b;
	}
	if (tryToParse(toVariant.text)) {
		toVariant.type = Variant::TEXT;
		return true;
	}
	return false;
}

template<typename T> bool Parser::tryToParseReal(T& r) {
	whiteAndComments();
	if (eof()) {
		return false;
	}
	const Char* const b = pointerAt(source, p);
	const Char* const e = pointerAt(source, source.end());
	const Char* const q = parseReal<T>(b, e, r);
	if (q == b) {
		return false;
	}
	const Char* const d = b + ((*b == '-' || *b == '+') ? 1 : 0);
	if (looksOctal(d, q)) {
		p = iteratorAt(source, d + 1);
		return false;
	}
	p = iteratorAt(source, q);
	whiteAndComments();
	return eof();
}

bool Parser::tryToParse(double& d) { return tryToParseReal(d); }
bool Parser::tryToParse(float& f) { return tryToParseReal(f); }

bool Parser::isEmpty() {
	whiteAndComments();
	return eof();
}

bool Parser::isBracketed() {
	whiteAndComments();
	return !eof() && *p == '{';
}

bool Parser::isQuoted() {
	whiteAndComments();
	return !eof() && (*p == '"' || *p == '\'');
}

static String reindent(const String& s, int tabCount) {
	const StringIt b = s.begin();
	const StringIt e = s.end();
	StringIt p = e;
	while (p != b && p[-1] != '\n') {
		--p;
	}
	int dropCount = 0;
	while (p != e && *p == '\t') {
		++dropCount;
		++p;
	}
	String indented;
	p = b;
	while (p != e) {
		int i = 0;
		while (p != e && *p == '\t' && i < dropCount) {
			++p;
			++i;
		}
		const StringIt q = p;
		while (p != e && *p != '\n') {
			++p;
		}
		if (p != e) {
			++p;
		}
		indented.insert(indented.end(), q, p);
		if (p != e) {
			for (int i = 0; i < tabCount; ++i) {
				indented += '\t';
			}
		}
	}
	return indented;
}

